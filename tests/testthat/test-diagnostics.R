test_that("incompatibilities carry checkable null-space relations", {
  X <- cbind(group_A = c(1, 0), group_B = c(0, 1), N = c(1, 1))
  totals <- c(group_A = 4, group_B = 6, N = 11)
  report <- analyze_inconsistency(X, totals, details = TRUE)
  expect_true(report$inconsistent)
  expect_equal(report$rank_X, 2)
  expect_equal(report$rank_augmented, 3)
  expect_equal(nrow(report$incompatibilities), 1)
  expect_lt(max(abs(X %*% t(report$coefficients))), 1e-12)
  expect_equal(as.numeric(report$coefficients %*% totals), report$relations$discrepancy)
  expect_true(all(report$incompatibilities$violated))
  expect_true(all(vapply(report$incompatibilities$margins,
    function(margins) setequal(margins, colnames(X)), logical(1))))
  expect_false(analyze_inconsistency(X, c(group_A = 4, group_B = 6, N = 10)))
  expect_output(print(report), "incompatible")
})

test_that("diagnostics handle zero columns, no columns, and full rank", {
  X <- cbind(nonempty = c(1, 2), empty = 0)
  report <- analyze_inconsistency(X, c(nonempty = 3, empty = -2), details = TRUE)
  expect_true(report$inconsistent)
  expect_true(any(vapply(report$incompatibilities$margins,
    function(margins) identical(margins, "empty"), logical(1))))
  expect_equal(analyze_inconsistency(diag(3), 1:3, details = TRUE)$rank_augmented, 3)
  report <- analyze_inconsistency(matrix(numeric(), 2, 0), numeric(), details = TRUE)
  expect_false(report$inconsistent); expect_equal(report$rank_X, 0)
  expect_equal(dim(report$coefficients), c(0L, 0L))
  X <- matrix(0, 2, 3)
  report <- analyze_inconsistency(X, c(1, -2, 0), details = TRUE)
  expect_equal(report$rank_X, 0); expect_equal(report$rank_augmented, 1)
  expect_equal(nrow(report$incompatibilities), 2)
})

test_that("diagnostic rank and target tolerances have separate roles", {
  X <- cbind(A = c(1,0), B = c(0,1), N = c(1,1))
  totals <- c(A=4,B=6,N=11)
  Xscaled <- sweep(X, 2, c(1e-8, 1e8, 3), "*")
  scaled <- analyze_inconsistency(Xscaled, totals*c(1e-8,1e8,3), details=TRUE)
  expect_true(scaled$inconsistent)
  expect_equal(scaled$rank_X, 2)
  expect_lt(max(abs(Xscaled %*% t(scaled$coefficients))), 1e-5)
  expect_false(analyze_inconsistency(X, c(A=4,B=6,N=10+1e-10), tol=1e-8))
  expect_true(analyze_inconsistency(X, c(A=4,B=6,N=10+1e-5), tol=1e-8))
})

test_that("preflight distinguishes algebraic and bounded infeasibility", {
  X <- cbind(A=c(1,0),B=c(0,1),N=c(1,1))
  report <- calibration_preflight(X,c(A=4,B=6,N=11),0,10)
  expect_equal(report$status,"inconsistent_totals")
  expect_equal(report$feasibility$solver,"rank")
  expect_equal(calibration_preflight(X,c(A=4,B=6,N=10),0,3)$status,"bound_infeasible")
  expect_equal(calibration_preflight(X,c(A=4,B=6,N=10),0,10)$status,"feasible")
})

test_that("workflows stop on conflicting totals unless merging is explicit", {
  # B is 2*A, but the supplied totals violate that equality.
  X <- cbind(A=c(1,0),B=c(2,0)); totals <- c(A=2,B=5)
  args <- list(X=X,totals=totals,d=c(1,1),lower=0,upper=10,
    bounds=c(0,10),search_limits=c(0,10),margin_groups=list(c("A","B")),ordered=TRUE)
  result <- do.call(automatic_calibration,args)
  expect_length(result,0)
  expect_equal(attr(result,"search_status"),"inconsistent_totals")
  expect_equal(attr(result,"searched_nodes"),0)
  expect_gt(nrow(attr(result,"preflight")$consistency$incompatibilities),0)
  expect_output(print(result),"incompatible")
  args$on_inconsistency <- "merge"
  result <- do.call(automatic_calibration,args)
  expect_length(result,1)
  expect_equal(sum(result[[1]]$residuals_original),0,tolerance=1e-7)
  expect_gt(max(abs(result[[1]]$residuals_original)),.1)
  args$on_inconsistency <- "stop"; args$choose <- function(candidates) stop("Should not be called")
  result <- do.call(interactive_calibration,args)
  expect_s3_class(result,"caltools_search")
  expect_equal(attr(result,"preflight")$status,"inconsistent_totals")
})

test_that("alternating projections return witnesses or an inconclusive status", {
  X <- rbind(c(-2,3),c(0,0),c(3,0),c(0,1))
  totals <- c(1.9,7.75)
  fit <- calibration_feasibility(X,totals,0,2,method="projection",max_iter=20000,fallback=FALSE)
  expect_true(fit$feasible)
  expect_lte(fit$max_scaled_residual,1e-8)
  fit <- calibration_feasibility(X,totals,0,2,method="projection",max_iter=1,fallback=FALSE)
  expect_true(is.na(fit$feasible))
  expect_equal(fit$status,"iteration_limit")
  expect_true(calibration_feasibility(X,totals,0,2,method="projection",max_iter=1)$feasible)
  X <- cbind(c(1,1),c(1,1))
  fit <- calibration_feasibility(X,c(1,2),0,3,method="projection",fallback=FALSE)
  expect_false(fit$feasible); expect_equal(fit$status,"inconsistent_totals")
})
